-- PARROTHIT PARROT SEARCH 2.0
-- Run once in Supabase SQL Editor. Public search exposes published stories only.
create extension if not exists pg_trgm;

create index if not exists parrothit_posts_search_v2_gin on public.posts using gin (
  to_tsvector('simple', coalesce(title,'')||' '||coalesce(summary,'')||' '||coalesce(body,'')||' '||coalesce(author_name,'')||' '||coalesce(source_name,'')||' '||coalesce(slug,'')||' '||coalesce(seo_title,'')||' '||coalesce(seo_description,''))
);
create index if not exists parrothit_posts_title_trgm on public.posts using gin (title gin_trgm_ops);
create index if not exists parrothit_posts_summary_trgm on public.posts using gin (summary gin_trgm_ops);

create table if not exists public.parrothit_search_analytics (
 id bigint generated by default as identity primary key,
 search_term text not null,
 result_count integer not null default 0,
 searched_at timestamptz not null default now()
);
create index if not exists parrothit_search_analytics_date_idx on public.parrothit_search_analytics(searched_at desc);
create index if not exists parrothit_search_analytics_term_idx on public.parrothit_search_analytics(lower(search_term));
alter table public.parrothit_search_analytics enable row level security;
revoke all on public.parrothit_search_analytics from anon, authenticated, public;

create or replace function public.parrothit_search_news_v2(
 p_search_term text, p_category text default null, p_since timestamptz default null,
 p_sort text default 'relevance', p_limit integer default 50
) returns table (
 id uuid, title text, slug text, summary text, body text, image_url text,
 category_id uuid, category_name text, author_name text, source_name text,
 published_at timestamptz, seo_title text, seo_description text, rank real
) language sql stable security definer set search_path=public,pg_temp as $$
 with input as (
  select trim(coalesce(p_search_term,'')) term,
         websearch_to_tsquery('simple',nullif(trim(coalesce(p_search_term,'')),'')) query
 ), candidates as (
  select p.id,p.title,p.slug,p.summary,p.body,p.image_url,p.category_id,c.name category_name,
         p.author_name,p.source_name,p.published_at,p.seo_title,p.seo_description,
         to_tsvector('simple',coalesce(p.title,'')||' '||coalesce(p.summary,'')||' '||coalesce(p.body,'')||' '||coalesce(p.author_name,'')||' '||coalesce(p.source_name,'')||' '||coalesce(p.slug,'')||' '||coalesce(p.seo_title,'')||' '||coalesce(p.seo_description,'')) doc,
         i.query,i.term
  from public.posts p left join public.categories c on c.id=p.category_id cross join input i
  where p.status='published' and (p.published_at is null or p.published_at<=now())
    and (p_category is null or c.name=p_category)
    and (p_since is null or p.published_at>=p_since)
 ), matched as (
  select x.*, case when x.query is not null then ts_rank_cd(x.doc,x.query) else 0 end
    + greatest(similarity(coalesce(x.title,''),x.term),similarity(coalesce(x.summary,''),x.term))*0.25 as score
  from candidates x
  where x.term<>'' and (
   (x.query is not null and x.doc@@x.query)
   or x.title ilike '%'||x.term||'%' or x.summary ilike '%'||x.term||'%'
   or x.body ilike '%'||x.term||'%' or x.author_name ilike '%'||x.term||'%'
   or x.source_name ilike '%'||x.term||'%' or x.category_name ilike '%'||x.term||'%'
   or similarity(coalesce(x.title,''),x.term)>0.18
   or similarity(coalesce(x.summary,''),x.term)>0.22
  )
 )
 select m.id,m.title,m.slug,m.summary,m.body,m.image_url,m.category_id,m.category_name,m.author_name,m.source_name,m.published_at,m.seo_title,m.seo_description,m.score::real
 from matched m
 order by case when lower(coalesce(p_sort,'relevance'))='newest' then extract(epoch from coalesce(m.published_at,'epoch'::timestamptz)) end desc nulls last,
          case when lower(coalesce(p_sort,'relevance'))='oldest' then extract(epoch from coalesce(m.published_at,'epoch'::timestamptz)) end asc nulls last,
          case when lower(coalesce(p_sort,'relevance')) not in ('newest','oldest') then m.score end desc nulls last,
          m.published_at desc nulls last
 limit greatest(1,least(coalesce(p_limit,50),100));
$$;
revoke all on function public.parrothit_search_news_v2(text,text,timestamptz,text,integer) from public;
grant execute on function public.parrothit_search_news_v2(text,text,timestamptz,text,integer) to anon,authenticated;

create or replace function public.parrothit_search_suggestions(search_prefix text,result_limit integer default 6)
returns table(suggestion text) language sql stable security definer set search_path=public,pg_temp as $$
 select distinct p.title::text from public.posts p
 where p.status='published' and (p.published_at is null or p.published_at<=now())
 and p.title ilike trim(coalesce(search_prefix,''))||'%'
 order by p.title limit greatest(1,least(coalesce(result_limit,6),10));
$$;
revoke all on function public.parrothit_search_suggestions(text,integer) from public;
grant execute on function public.parrothit_search_suggestions(text,integer) to anon,authenticated;

create or replace function public.parrothit_log_search(search_term text,result_count integer default 0)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if length(trim(coalesce(search_term,''))) between 2 and 160 then
  insert into public.parrothit_search_analytics(search_term,result_count)
  values(left(trim(search_term),160),greatest(0,least(coalesce(result_count,0),1000)));
 end if;
end;$$;
revoke all on function public.parrothit_log_search(text,integer) from public;
grant execute on function public.parrothit_log_search(text,integer) to anon,authenticated;

create or replace function public.parrothit_trending_searches(result_limit integer default 6)
returns table(search_term text,searches bigint) language sql stable security definer set search_path=public,pg_temp as $$
 select min(a.search_term) search_term,count(*) searches
 from public.parrothit_search_analytics a
 where a.searched_at>now()-interval '7 days'
 group by lower(a.search_term)
 order by count(*) desc
 limit greatest(1,least(coalesce(result_limit,6),10));
$$;
revoke all on function public.parrothit_trending_searches(integer) from public;
grant execute on function public.parrothit_trending_searches(integer) to anon,authenticated;

-- Admin-only analytics view. Existing admin authentication is enforced in the page;
-- the view itself is not exposed to anon/authenticated browser roles.
create or replace view public.parrothit_search_admin_summary as
select count(*) filter(where searched_at>now()-interval '7 days') searches_last_7_days,
       count(*) filter(where searched_at>now()-interval '7 days' and result_count=0) zero_result_searches,
       count(distinct lower(search_term)) distinct_terms_last_7_days
from public.parrothit_search_analytics;
revoke all on public.parrothit_search_admin_summary from public,anon,authenticated;

create or replace function public.parrothit_search_admin_analytics()
returns table(searches_last_7_days bigint,zero_result_searches bigint,top_terms jsonb)
language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
 if not exists(select 1 from public.admin_profiles ap where ap.user_id=auth.uid() and coalesce(ap.is_suspended,false)=false) then
  raise exception 'Administrator access required';
 end if;
 return query
 select (select count(*) from public.parrothit_search_analytics where searched_at>now()-interval '7 days'),
        (select count(*) from public.parrothit_search_analytics where searched_at>now()-interval '7 days' and result_count=0),
        (select coalesce(jsonb_agg(jsonb_build_object('term',term,'count',n) order by n desc),'[]'::jsonb) from
          (select min(search_term) term,count(*) n from public.parrothit_search_analytics where searched_at>now()-interval '30 days' group by lower(search_term) order by count(*) desc limit 20) t);
end;$$;
revoke all on function public.parrothit_search_admin_analytics() from public;
grant execute on function public.parrothit_search_admin_analytics() to authenticated;
